"""Writes m3x-loading.css: a contained loading indicator whose shape morphs through the M3X sequence. Usage: gen_loading.py OUT.css
Every shape is a polar curve sampled at the same N angles, so clip-path can interpolate between them."""
import math, sys

N = 48

def lobes(k, amp, base=1.0):
    return lambda t: base * (1 - amp + amp * math.cos(k * t))

def polygon(n_sides, rounding):
    # Rounded regular polygon: blend between the polygon's radius and a circle.
    def r(t):
        a = math.pi / n_sides
        x = (t + math.pi / 2) % (2 * a) - a
        poly = math.cos(a) / math.cos(x)
        return (1 - rounding) * poly + rounding
    return r

def pill(t):
    # Superellipse-ish capsule, wider than tall.
    a, b, p = 1.0, .62, 3.2
    c, s = abs(math.cos(t)), abs(math.sin(t))
    return (c ** p / a ** p + s ** p / b ** p) ** (-1 / p)

SHAPES = [  # name, r(theta) (max 1)
    ("soft-burst", lobes(10, .17)),
    ("cookie-9", lobes(9, .11)),
    ("pentagon", polygon(5, .35)),
    ("pill", pill),
    ("sunny", lobes(8, .06)),
    ("cookie-4", lobes(4, .13)),
    ("oval", lambda t: 1 / math.sqrt((math.cos(t) / 1) ** 2 + (math.sin(t) / .78) ** 2)),
]

def pts(r):
    out = []
    for i in range(N):
        t = 2 * math.pi * i / N - math.pi / 2
        rr = r(t)
        out.append(f"{50 + 50 * rr * math.cos(t):.1f}% {50 + 50 * rr * math.sin(t):.1f}%")
    return "polygon(" + ", ".join(out) + ")"

frames = []
step = 100 / len(SHAPES)
for i, (name, r) in enumerate(SHAPES + [SHAPES[0]]):
    frames.append(f"  {i * step:.2f}% {{ clip-path: {pts(r)}; }} /* {name if i < len(SHAPES) else SHAPES[0][0]} */")

css = f"""/* Contained loading indicator (M3X): a 48px container, a 38px shape that morphs and turns.
   Generated by ../tools/gen_loading.py: {len(SHAPES)} shapes, {N} points each, so clip-path can interpolate them. */
.m3x-loading {{
  flex: none; width: 48px; height: 48px; border-radius: 50%; display: grid; place-items: center;
  background: var(--primary-container);
}}
.m3x-loading.bare {{ background: none; }}
.m3x-loading > i {{
  width: 38px; height: 38px; background: var(--primary);
  animation: m3x-morph 4.9s var(--spring) infinite, m3x-turn 4.9s linear infinite;
}}
.m3x-loading.small {{ width: 32px; height: 32px; }}
.m3x-loading.small > i {{ width: 24px; height: 24px; }}
@keyframes m3x-turn {{ to {{ transform: rotate(720deg); }} }}
@keyframes m3x-morph {{
{chr(10).join(frames)}
}}
@media (prefers-reduced-motion: reduce) {{
  .m3x-loading > i {{ animation: m3x-turn 6s linear infinite; clip-path: {pts(SHAPES[1][1])}; }}
}}
"""
open(sys.argv[1], "w").write(css)
print("wrote", sys.argv[1], len(css), "bytes")
